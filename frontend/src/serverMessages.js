// The language I18nProvider set on <html>; outside a browser (unit tests),
// messages are left as the server sent them.
const currentLocale = () =>
  typeof document === 'undefined' ? 'en' : document.documentElement.lang || 'fr';

// Returns the message in the interface language when it is a known server
// message, the message unchanged otherwise.
export function translateServerMessage(message, locale = currentLocale()) {
  if (!message || !String(locale).startsWith('fr')) return message;
  const text = String(message).trim();
  if (FR[text]) return FR[text];
  for (const [pattern, replacement] of FR_PATTERNS) {
    if (pattern.test(text)) return text.replace(pattern, replacement);
  }
  return message;
}
