#!/usr/bin/env python3
"""EndoriumFort — migrate an existing SQLite store to PostgreSQL.

Emits a single SQL transaction on stdout; nothing is written to either
database by this script, so the output can be reviewed before it is applied.
Only the Python standard library is used, so it runs anywhere psql does.

  1. Stop the bastion.
  2. Create the schema on PostgreSQL by starting the bastion once against the
     new DSN and stopping it again (it creates its own tables), e.g.
       ENDORIUMFORT_DB_DSN=postgresql://... endoriumfort_backend
  3. Generate and apply the data. That first start seeded a default admin, so
     the target is no longer empty and --replace is what you want here:
       scripts/migrate-sqlite-to-postgres.py --replace /app/data/endoriumfort.db > load.sql
       psql "postgresql://..." -v ON_ERROR_STOP=1 -f load.sql
  4. Restart the bastion with ENDORIUMFORT_DB_DSN set.

By default the generated script refuses to run if the target tables already
hold rows, so it cannot silently merge into a live database. --replace instead
empties those tables first, in the same transaction as the load: use it on a
target that holds nothing but the bastion's own seed rows, never on a database
that has been in service. Identity sequences are advanced past the imported ids
at the end, otherwise the first new insert would collide.
"""

import argparse
import sqlite3
import sys


def quote_ident(name: str) -> str:
    return '"' + name.replace('"', '""') + '"'


def quote_value(value) -> str:
    if value is None:
        return "NULL"
    if isinstance(value, bool):
        return "TRUE" if value else "FALSE"
    if isinstance(value, int):
        return str(value)
    if isinstance(value, float):
        return repr(value)
    if isinstance(value, (bytes, bytearray)):
        # PostgreSQL bytea hex input.
        return "'\\x" + bytes(value).hex() + "'"
    text = str(value)
    # standard_conforming_strings is on by default, so only quotes need doubling.
    return "'" + text.replace("'", "''") + "'"


def table_order(con: sqlite3.Connection, tables):
    """Parents before children, so foreign keys are satisfied as we load."""
    deps = {t: set() for t in tables}
    for t in tables:
        for row in con.execute(f"PRAGMA foreign_key_list({quote_ident(t)})"):
            parent = row[2]
            if parent in deps and parent != t:
                deps[t].add(parent)

    ordered, seen = [], set()
    # Deterministic output: walk alphabetically, emitting parents first.
    def visit(t, trail):
        if t in seen:
            return
        if t in trail:  # cycle — break it, FKs between these must be deferrable
            return
        for parent in sorted(deps[t]):
            visit(parent, trail | {t})
        seen.add(t)
        ordered.append(t)

    for t in sorted(tables):
        visit(t, set())
    return ordered


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("sqlite_path", help="path to endoriumfort.db")
    ap.add_argument("--allow-nonempty", action="store_true",
                    help="skip the guard that refuses a non-empty target")
    ap.add_argument("--replace", action="store_true",
                    help="empty the target tables first (for a schema the bastion "
                         "just created and seeded); implies --allow-nonempty")
    args = ap.parse_args()
    if args.replace:
        args.allow_nonempty = True

    con = sqlite3.connect(f"file:{args.sqlite_path}?mode=ro", uri=True)
    # Default factory: TEXT comes back as str and BLOB as bytes, which is the
    # distinction quote_value() needs. Tolerate rows that are not valid UTF-8
    # rather than aborting a migration over one bad byte.
    con.text_factory = lambda b: b.decode("utf-8", errors="replace")

    tables = [r[0] for r in con.execute(
        "SELECT name FROM sqlite_master WHERE type='table' "
        "AND name NOT LIKE 'sqlite_%' ORDER BY name")]
    if not tables:
        print(f"no tables found in {args.sqlite_path}", file=sys.stderr)
        return 1

    out = sys.stdout
    out.write("-- Generated by scripts/migrate-sqlite-to-postgres.py\n")
    out.write(f"-- Source: {args.sqlite_path}\n")
    out.write("-- Apply with: psql \"<dsn>\" -v ON_ERROR_STOP=1 -f this_file.sql\n")
    out.write("-- (this file opens its own transaction; do not add psql -1)\n\n")
    out.write("BEGIN;\n\n")

    ordered = table_order(con, tables)

    if args.replace:
        # Same transaction as the load: either the target is replaced in full
        # or nothing changes. Only the tables we are about to load are emptied,
        # so anything the target holds that the source does not know about is
        # left alone. CASCADE covers foreign keys between them.
        out.write("-- Replace the contents of the tables being imported.\n")
        out.write("TRUNCATE " + ", ".join(quote_ident(t) for t in ordered) +
                  " RESTART IDENTITY CASCADE;\n\n")

    if not args.allow_nonempty:
        out.write("-- Refuse to merge into a database that already holds data.\n")
        out.write("DO $$\nDECLARE n bigint;\nBEGIN\n")
        for t in ordered:
            out.write(f"  SELECT count(*) INTO n FROM {quote_ident(t)};\n")
            out.write(f"  IF n > 0 THEN RAISE EXCEPTION "
                      f"'target table {t} already holds % rows; "
                      f"start from an empty database or pass --allow-nonempty', n; END IF;\n")
        out.write("END $$;\n\n")

    total = 0
    for t in ordered:
        cols = [r[1] for r in con.execute(f"PRAGMA table_info({quote_ident(t)})")]
        if not cols:
            continue
        rows = con.execute(f"SELECT {', '.join(quote_ident(c) for c in cols)} "
                           f"FROM {quote_ident(t)}").fetchall()
        out.write(f"-- {t}: {len(rows)} row(s)\n")
        collist = ", ".join(quote_ident(c) for c in cols)
        for row in rows:
            values = [quote_value(v) for v in row]
            out.write(f"INSERT INTO {quote_ident(t)} ({collist}) "
                      f"VALUES ({', '.join(values)});\n")
        total += len(rows)
        out.write("\n")

    out.write("-- Advance identity sequences past the imported ids.\n")
    out.write("DO $$\nDECLARE r record; seq text;\nBEGIN\n"
              "  FOR r IN SELECT c.table_name, c.column_name\n"
              "           FROM information_schema.columns c\n"
              "           WHERE c.table_schema = current_schema()\n"
              "             AND c.is_identity = 'YES'\n"
              "  LOOP\n"
              "    seq := pg_get_serial_sequence(quote_ident(r.table_name), r.column_name);\n"
              "    IF seq IS NOT NULL THEN\n"
              "      EXECUTE format('SELECT setval(%L, COALESCE((SELECT MAX(%I) FROM %I), 0) + 1, false)',\n"
              "                     seq, r.column_name, r.table_name);\n"
              "    END IF;\n"
              "  END LOOP;\n"
              "END $$;\n\n")

    out.write("COMMIT;\n")
    print(f"{len(ordered)} table(s), {total} row(s) emitted", file=sys.stderr)
    return 0


if __name__ == "__main__":
    sys.exit(main())
